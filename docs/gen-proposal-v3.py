def p(text, bold=False, color=None, indent=True):
    para = doc.add_paragraph()
    para.paragraph_format.first_line_indent = Cm(0.74) if indent else Cm(0)
    para.paragraph_format.line_spacing = 1.6
    run = para.add_run(text)
    if bold: run.bold = True
    if color: run.font.color.rgb = color
    return para

def bullet(text, level=0):
    para = doc.add_paragraph(style='List Bullet')
    para.paragraph_format.left_indent = Cm(0.6 + level * 0.6)
    para.paragraph_format.line_spacing = 1.5
    para.add_run(text)
    return para

def kv(items):
    """加粗 key + 普通 value 的段落组，items = [(key, value)]"""
    for k, v in items:
        para = doc.add_paragraph()
        para.paragraph_format.first_line_indent = Cm(0.74)
        para.paragraph_format.line_spacing = 1.55
        r1 = para.add_run(k)
        r1.bold = True
        para.add_run('：' + v)

def add_table(headers, rows, widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Light Grid Accent 1'
    # 表头
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        for para in cell.paragraphs:
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for run in para.runs:
                run.bold = True
                run.font.size = Pt(10.5)
    # 数据行
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.rows[i + 1].cells[j]
            cell.text = str(val)
            for para in cell.paragraphs:
                for run in para.runs:
                    run.font.size = Pt(10)
    # 列宽
    if widths:
        for col_idx, w in enumerate(widths):
            for row in table.rows:
                row.cells[col_idx].width = Cm(w)
    return table

